#!/usr/bin/env python3
"""Turn supabase/seed/tools-opening-csl.csv (the container list, cleaned) into supabase/seed/tools-opening-csl.sql.

Edit the CSV (in Excel or any editor), then run:   python3 scripts/tools-seed.py
The SQL adds every item to the catalogue and records its quantity as opening stock at the CSL site. Run the SQL yourself in the Supabase SQL editor,
after 2026-11-tools-register.sql. It refuses to run twice (it stops if CSL already has opening stock).
"""
import csv, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "supabase/seed/tools-opening-csl.csv"
OUT = ROOT / "supabase/seed/tools-opening-csl.sql"
q = lambda s: "'" + str(s).replace("'", "''") + "'"

rows = list(csv.DictReader(SRC.open(newline="", encoding="utf-8")))
vals = []
for i, r in enumerate(rows):
    good, dmg = float(r["good"] or 0), float(r["damaged"] or 0)
    if r["kind"] not in ("tool", "consumable"): raise SystemExit(f"row {i + 2}: kind must be tool or consumable")
    if good < 0 or dmg < 0: raise SystemExit(f"row {i + 2}: quantities cannot be negative")
    vals.append(f"({q(r['category'])}, {q(r['name'])}, {q(r['spec'])}, {q(r['unit'] or 'Nos')}, {q(r['kind'])}, {good:g}, {dmg:g}, {q(r['note'])}, {(i + 1) * 10})")

OUT.write_text(f"""-- Opening stock at CSL: the tools and materials that went to the site in the container, before the app was used.
-- Made by scripts/tools-seed.py from tools-opening-csl.csv ({len(rows)} items). Do not edit this file: edit the CSV and run the script again.
-- NOT run by Claude: run it yourself in the Supabase SQL editor, AFTER 2026-11-tools-register.sql. It stops if CSL already has opening stock.
-- Change the date below if the container reached the site on another day.
do $$
declare csl uuid; n int; opening_on date := (now() at time zone 'Asia/Kolkata')::date;
begin
  select count(*) into n from public.projects where lower(btrim(name)) = 'csl';
  if n <> 1 then raise exception 'Expected exactly one project named CSL, found %.', n; end if;
  select id into csl from public.projects where lower(btrim(name)) = 'csl';
  if exists (select 1 from public.tool_moves where project_id = csl and kind = 'opening' and voided_at is null) then raise exception 'CSL already has opening stock. Nothing was changed.'; end if;

  create temp table _seed (category text, name text, spec text, unit text, kind text, good numeric, damaged numeric, note text, sort_order int) on commit drop;
  insert into _seed values
    {(',' + chr(10) + '    ').join(vals)};

  -- the catalogue (an item already there is reused)
  insert into public.tool_items (category, name, spec, unit, kind, note, sort_order)
  select s.category, s.name, s.spec, s.unit, s.kind, s.note, s.sort_order from _seed s
  where not exists (select 1 from public.tool_items t where lower(btrim(t.category)) = lower(btrim(s.category)) and lower(btrim(t.name)) = lower(btrim(s.name)) and lower(btrim(t.spec)) = lower(btrim(s.spec)));

  -- the opening stock
  insert into public.tool_moves (item_id, project_id, kind, d_ok, d_damaged, moved_on, note)
  select t.id, csl, 'opening', s.good, s.damaged, opening_on, 'Container list (before the app)' from _seed s
  join public.tool_items t on lower(btrim(t.category)) = lower(btrim(s.category)) and lower(btrim(t.name)) = lower(btrim(s.name)) and lower(btrim(t.spec)) = lower(btrim(s.spec))
  where s.good > 0 or s.damaged > 0;
end $$;
""", encoding="utf-8")
print(f"Wrote {OUT.relative_to(ROOT)} ({len(rows)} items)")
